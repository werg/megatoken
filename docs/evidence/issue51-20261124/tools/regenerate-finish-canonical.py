from pathlib import Path
import json
import os
import subprocess
import sys
import time

root = Path(__file__).parent
repo = root / 'producer-dev'
env = dict(os.environ)
env['PATH'] = str(root / 'node24/node_modules/.bin') + os.pathsep + env['PATH']
commands = [
 ['node', 'tools/generate-semantic-region-contract.mjs', '--definition-only'],
 ['node', 'tools/generate-protocol-machine-fixtures.mjs'],
 ['node', 'tools/generate-protocol-iterator-fixtures.mjs'],
 ['node', 'tools/generate-protocol-generator-fixtures.mjs'],
 ['node', 'tools/generate-protocol-iterator-source-fixtures.mjs'],
 ['node', 'tools/generate-protocol-host-fixtures.mjs'],
 ['node', 'tools/generate-primitive-conversion-fixtures.mjs'],
 ['node', 'tools/generate-protocol-source-fixtures.mjs'],
 ['node', 'tools/generate-semantic-region-contract.mjs'],
 ['npm', 'run', 'contracts:check'],
]
revision = subprocess.check_output(['git','rev-parse','HEAD'], cwd=repo, text=True).strip()
if sys.argv[1:] == ['--resume-final-check']:
 status = json.loads((root / 'finish-canonical-status.json').read_bytes())
 assert status['producerRevision'] == revision
 assert status['current'] is None
 assert len(status['steps']) == 9
 assert [step['command'] for step in status['steps']] == commands[:9]
 assert all(step['exitCode'] == 0 for step in status['steps'])
 assert all(Path(step['log']).is_file() for step in status['steps'])
 contract = json.loads((repo / 'contracts/semantic-execution-v8.json').read_bytes())
 policy = json.loads((repo / 'contracts/semantic-native-policy-v8.json').read_bytes())
 previous_policy = json.loads(subprocess.check_output(
     ['git','show','HEAD:contracts/semantic-native-policy-v8.json'], cwd=repo))
 assert all(policy[key] == contract['digest' if key == 'contractDigest' else key] for key in
            ('contractDigest','fixtureDigest','interoperabilityDigest'))
 assert {key for key in policy if policy[key] != previous_policy[key]} <= {
     'contractDigest','fixtureDigest','interoperabilityDigest'}
 assert policy.keys() == previous_policy.keys()
 (root / 'finish-canonical-generation-prefix.json').write_text(json.dumps(status, indent=2) + '\n')
 status['orchestrationRecovery'] = {
     'reason': 'The save allowlist omitted the native policy generated by the full contract generator. Its digest-only change was audited and added to the allowlist.',
     'resumedAtStep': 9,
     'preservedSuccessfulGeneratorSteps': list(range(9)),
     'sourceRevisionUnchanged': revision,
 }
 first = 9
else:
 assert not sys.argv[1:], 'Only --resume-final-check is supported'
 status = {'producerRevision': revision, 'steps': []}
 assert not subprocess.check_output(['git','status','--porcelain'], cwd=repo, text=True)
 first = 0
for index in range(first, len(commands)):
 command = commands[index]
 if index == 9:
  changed = subprocess.check_output(['git','diff','--name-only'], cwd=repo, text=True).splitlines()
  allowed_contracts = {'contracts/semantic-execution-v8.json', 'contracts/semantic-native-policy-v8.json'}
  assert all(path in allowed_contracts or path.startswith('test/fixtures/semantic-') for path in changed), changed
  assert not subprocess.check_output(['git','ls-files','--others','--exclude-standard'], cwd=repo, text=True)
  if changed:
   subprocess.run(['git','add','--',*changed], cwd=repo, check=True)
   subprocess.run(['git','commit','-m','Regenerate paired object semantics source and execution fixtures'], cwd=repo, check=True)
  assert not subprocess.check_output(['git','status','--porcelain'], cwd=repo, text=True)
  status['implementationRevision'] = status['producerRevision']
  status['producerRevision'] = subprocess.check_output(['git','rev-parse','HEAD'], cwd=repo, text=True).strip()
 log = root / ('finish-canonical-%02d.log' % index)
 status['current'] = {'command': command, 'log': str(log)}
 (root / 'finish-canonical-status.json').write_text(json.dumps(status, indent=2) + '\n')
 print('START', index, ' '.join(command), flush=True)
 start = time.monotonic()
 with log.open('w') as stream:
  result = subprocess.run(command, cwd=repo, env=env, stdout=stream, stderr=subprocess.STDOUT)
 status['steps'].append({'command': command, 'log': str(log), 'exitCode': result.returncode, 'seconds': round(time.monotonic()-start, 3)})
 status['current'] = None
 (root / 'finish-canonical-status.json').write_text(json.dumps(status, indent=2) + '\n')
 print('DONE', index, result.returncode, flush=True)
 if result.returncode:
  raise SystemExit(result.returncode)
print('ALL CANONICAL GENERATORS AND STANDARD CONTRACT GATE PASSED', flush=True)
